import matplotlib.pyplot as plt
import random

def simulate_strategy(strategy, num_simulations, num_games, starting_bankroll):
  profits = []
  drawdowns = []
  ruin_count = 0
  for simulation in range(num_simulations):
        bankroll = starting_bankroll
        peak = bankroll
        max_drawdown = 0

        for trial in range(num_games):
            if random.random() < strategy["win_probability"]:
              money = strategy["win_profit"]
            else:
              money = strategy["loss_profit"]
            bankroll += money
            if bankroll > peak:
              peak = bankroll
            drawdown = peak - bankroll
            if drawdown > max_drawdown:
              max_drawdown = drawdown
            if bankroll <= 0:
              ruin_count += 1
              break
        drawdowns.append(max_drawdown)
        profits.append(bankroll - starting_bankroll)

  average_profit = sum(profits) / len(profits)
  average_drawdown = sum(drawdowns) / len(drawdowns)

  squared_differences = 0

  for profit in profits:
        difference = (profit - average_profit)
        squared_difference = difference * difference
        squared_differences = squared_difference + squared_differences
  variance = squared_differences / len(profits)
  standard_deviation = variance ** 0.5
  ruin_probability = ruin_count / num_simulations

  p = ruin_probability
  n = num_simulations
  standard_error = (p * (1-p) / n) **0.5
  margin_error = (1.96 * standard_error)

  lower_bound = p - margin_error
  upper_bound = p + margin_error
  return average_profit, average_drawdown, standard_deviation, ruin_probability, lower_bound, upper_bound

strategies = [
    {
        "name": "A",
        "win_probability": 1/6,
        "win_profit": 11,
        "loss_profit": -2
    },
    {
        "name": "B",
        "win_probability": 1/3,
        "win_profit": 5,
        "loss_profit": -2
    }
]
for strategy in strategies:
  profit, drawdown, std_dev, ruin, l_bound, u_bound = simulate_strategy(strategy, 1000, 200, 20)

  print(f"Strategy {strategy['name']}")
  print(f"Average profit: ${profit:.2f}")
  print(f"Average drawdown: ${drawdown:.2f}")
  print(f"Standard deviation: ${std_dev:.2f}")
  print(f"Probability of ruin: {ruin:.2%}")
  print(f"95% CI: {l_bound:.2%} to {u_bound:.2%}")
  print()